"""Extract 100 m WorldPop 2020 grids for the game cities.

Source: WorldPop Total Population 100m ImageServer, CC BY 4.0.
https://worldpop.arcgis.com/arcgis/rest/services/WorldPop_Total_Population_100m/ImageServer
"""

import base64
from io import BytesIO
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

from PIL import Image


CITIES = {
    # Keep these extraction bounds in sync with cityConfigs[*].mapBounds in src/main.ts.
    "seoul": {"south": 37.38, "west": 126.65, "north": 37.76, "east": 127.3},
    "busan": {"south": 34.98, "west": 128.72, "north": 35.42, "east": 129.35},
    "daejeon": {"south": 36.17, "west": 127.2, "north": 36.55, "east": 127.62},
    "gwangju": {"south": 35.02, "west": 126.62, "north": 35.32, "east": 127.1},
}
CELL_SIZE = 1 / 1200  # 3 arc-seconds, approximately 100 m at the equator.
ENDPOINT = "https://worldpop.arcgis.com/arcgis/rest/services/WorldPop_Total_Population_100m/ImageServer/exportImage"
OUTPUT = Path("src/data/worldPopKorea2020.ts")


def fetch_grid(bounds):
    south, west = bounds["south"], bounds["west"]
    north, east = bounds["north"], bounds["east"]
    columns = round((east - west) / CELL_SIZE)
    rows = round((north - south) / CELL_SIZE)
    query = urlencode({
        "bbox": f"{west},{south},{east},{north}",
        "bboxSR": "4326",
        "size": f"{columns},{rows}",
        "imageSR": "4326",
        "time": "1577836800000",
        "format": "tiff",
        "pixelType": "F32",
        "interpolation": "RSP_NearestNeighbor",
        "f": "image",
    })
    with urlopen(f"{ENDPOINT}?{query}") as response:
        image = Image.open(BytesIO(response.read()))
        values = [max(0, min(65535, round(value))) if value < 1e20 else 0 for value in image.getdata()]
    return north, west, image.width, image.height, values


def main():
    grids = {city: fetch_grid(bounds) for city, bounds in CITIES.items()}
    lines = [
        "// Generated by scripts/build-worldpop-data.py. Do not edit manually.",
        "// Source: WorldPop 2020 South Korea 100 m population counts (CC BY 4.0).",
        "export type PopulationCityId = \"seoul\" | \"busan\" | \"daejeon\" | \"gwangju\";",
        "export type PopulationGrid = { north: number; west: number; columns: number; rows: number; values: string };",
        "export const worldPopKorea2020: Record<PopulationCityId, PopulationGrid> = {",
    ]
    for city, (north, west, columns, rows, values) in grids.items():
        encoded = base64.b64encode(bytearray().join(value.to_bytes(2, "little") for value in values)).decode("ascii")
        lines.append(f"  {city}: {{ north: {north}, west: {west}, columns: {columns}, rows: {rows}, values: [")
        lines.extend(f"    \"{encoded[index:index + 120]}\"," for index in range(0, len(encoded), 120))
        lines.append("  ].join(\"\") },")
    lines.extend(["};", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(", ".join(f"{city}: {grid[2]}x{grid[3]} cells" for city, grid in grids.items()))


if __name__ == "__main__":
    main()
